import { normalizePath, type App } from "obsidian";
import { ensureVaultFolder } from "./vaultFolders";
import { toSafeVaultFileName } from "./vaultFileName";

/** Where chat saves generated images and videos, whichever agent made them. */
export const GENERATED_IMAGES_FOLDER = "SystemSculpt/Images";
export const GENERATED_VIDEOS_FOLDER = "SystemSculpt/Videos";

const EXTENSIONS: Readonly<Record<string, string>> = {
  "image/png": "png", "image/jpeg": "jpg", "image/webp": "webp", "image/gif": "gif",
  "video/mp4": "mp4", "video/webm": "webm", "video/quicktime": "mov",
};

/** The image type its leading bytes declare, or null for anything else. */
export function sniffImageMimeType(bytes: Uint8Array): "image/png" | "image/jpeg" | "image/webp" | "image/gif" | null {
  const at = (index: number) => bytes[index];
  if (at(0) === 0x89 && at(1) === 0x50 && at(2) === 0x4e && at(3) === 0x47) return "image/png";
  if (at(0) === 0xff && at(1) === 0xd8 && at(2) === 0xff) return "image/jpeg";
  if (at(0) === 0x47 && at(1) === 0x49 && at(2) === 0x46) return "image/gif";
  if (String.fromCharCode(...bytes.subarray(0, 4)) === "RIFF" && String.fromCharCode(...bytes.subarray(8, 12)) === "WEBP") return "image/webp";
  return null;
}

/**
 * Saves generated bytes as an ordinary vault file named by time and the
 * prompt's first words, and returns its vault path.
 */
export async function saveGeneratedMedia(app: App, options: {
  folder: string; prompt: string; bytes: ArrayBuffer; mimeType: string; now: Date; index?: number; count?: number;
}): Promise<string> {
  const { folder, prompt, bytes, mimeType, now, index = 0, count = 1 } = options;
  const extension = EXTENSIONS[mimeType] ?? (mimeType.startsWith("video/") ? "mp4" : "png");
  const pad = (value: number) => String(value).padStart(2, "0");
  const stamp = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
  const words = prompt.replace(/\s+/g, " ").trim().split(" ").slice(0, 8).join(" ");
  const stem = toSafeVaultFileName(`${stamp} ${words}${count > 1 ? ` ${index + 1}` : ""}`, { fallback: stamp, maxBytes: 120 });
  await ensureVaultFolder(app, folder);
  let path = normalizePath(`${folder}/${stem}.${extension}`);
  for (let suffix = 2; await app.vault.adapter.exists(path); suffix += 1) {
    path = normalizePath(`${folder}/${stem} ${suffix}.${extension}`);
  }
  await app.vault.createBinary(path, bytes);
  return path;
}
