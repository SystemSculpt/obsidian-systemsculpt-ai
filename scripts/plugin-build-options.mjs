import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

export const pluginBanner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

export const CANONICAL_API_BASE_URL = 'https://systemsculpt.com/api/plugin';

export const builtinExternals = [
  'node:*',
  'child_process', 'crypto', 'fs', 'fs/promises', 'http', 'https',
  'os', 'path', 'process', 'stream', 'stream/web', 'url', 'util',
];

export const AGENTS_CHAT_REACT_ENTRYPOINT = fs.realpathSync(
  require.resolve('agents/chat/react'),
);

const HEADLESS_REACT_IMPORT_PATTERN = /^(?:react|@ai-sdk\/react)$/;

function resolvedPath(filePath) {
  try {
    return fs.realpathSync(filePath);
  } catch {
    return path.resolve(filePath);
  }
}

/**
 * `agents/chat/react` is the maintained export for WebSocketChatTransport, but
 * its React hook imports are unused by this headless Obsidian client. Tell
 * esbuild those two imports are side-effect-free only at that exact importer;
 * direct React consumers elsewhere retain normal package semantics.
 */
export function createHeadlessAgentChatTreeShakingPlugin({
  importer = AGENTS_CHAT_REACT_ENTRYPOINT,
} = {}) {
  const resolvedImporter = resolvedPath(importer);
  const recursiveResolution = Symbol('headless-agent-chat-resolution');

  return {
    name: 'headless-agent-chat-tree-shaking',
    setup(build) {
      build.onResolve({ filter: HEADLESS_REACT_IMPORT_PATTERN }, async (args) => {
        if (
          args.pluginData === recursiveResolution ||
          resolvedPath(args.importer) !== resolvedImporter
        ) {
          return undefined;
        }
        const resolution = await build.resolve(args.path, {
          importer: args.importer,
          namespace: args.namespace,
          resolveDir: args.resolveDir,
          kind: args.kind,
          pluginData: recursiveResolution,
          with: args.with,
        });
        if (resolution.errors.length > 0) return resolution;
        return {
          ...resolution,
          sideEffects: false,
        };
      });
    },
  };
}

export function normalizeApiBaseUrl(value = CANONICAL_API_BASE_URL) {
  const raw = String(value || '').trim().replace(/\/+$/, '');
  let parsed;
  try {
    parsed = new URL(raw);
  } catch {
    throw new Error('SYSTEMSCULPT_API_BASE_URL must be an absolute HTTP(S) URL');
  }
  if (
    !['http:', 'https:'].includes(parsed.protocol) ||
    parsed.username ||
    parsed.password ||
    parsed.search ||
    parsed.hash
  ) {
    throw new Error(
      'SYSTEMSCULPT_API_BASE_URL must be an absolute HTTP(S) URL without credentials, query, or hash',
    );
  }
  if (parsed.pathname !== '/api/plugin') {
    throw new Error('SYSTEMSCULPT_API_BASE_URL must end with /api/plugin');
  }
  return raw;
}

export function resolvePluginBuildStamp({
  version,
  override,
  production = true,
} = {}) {
  const explicit = String(override || '').trim();
  if (explicit) return explicit;
  if (!production) return 'dev';

  const releaseVersion = String(version || '').trim();
  if (!/^\d+\.\d+\.\d+$/.test(releaseVersion)) {
    throw new Error('Production plugin builds require a semantic manifest version');
  }
  return `release-${releaseVersion}`;
}

export function createPluginBuildOptions({
  entryPoint = 'src/main.ts',
  outfile = 'main.js',
  write = true,
  production = true,
  overrides = {},
  plugins = [],
  buildStamp = 'dev',
  apiBaseUrl = CANONICAL_API_BASE_URL,
} = {}) {
  const normalizedApiBaseUrl = normalizeApiBaseUrl(apiBaseUrl);
  return {
    banner: { js: pluginBanner },
    entryPoints: [entryPoint],
    bundle: true,
    alias: {
      'onnxruntime-node': 'onnxruntime-web',
    },
    define: {
      '__SS_BUILD_STAMP__': JSON.stringify(buildStamp),
      '__SYSTEMSCULPT_API_BASE_URL__': JSON.stringify(normalizedApiBaseUrl),
    },
    external: [
      'obsidian', 'electron', 'proper-lockfile', 'graceful-fs',
      '@codemirror/autocomplete', '@codemirror/collab', '@codemirror/commands',
      '@codemirror/language', '@codemirror/lint', '@codemirror/search',
      '@codemirror/state', '@codemirror/view', '@lezer/common', '@lezer/highlight', '@lezer/lr',
      ...builtinExternals,
    ],
    format: 'cjs',
    target: 'es2018',
    logLevel: 'error',
    sourcemap: production ? false : 'inline',
    treeShaking: true,
    outfile,
    write,
    loader: { '.wasm': 'file' },
    plugins: [
      createHeadlessAgentChatTreeShakingPlugin(),
      ...plugins,
    ],
    ...overrides,
  };
}
